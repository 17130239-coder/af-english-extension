/**
 * AF English - YouTube Injected Script (Runs in page context: MAIN world)
 * Extracts full YouTube caption tracks directly from movie_player or ytInitialPlayerResponse.
 */

(function () {
  'use strict';

  if (window.__afYoutubeInjected) return;
  window.__afYoutubeInjected = true;

  function dispatchToContent(type, data) {
    try {
      window.dispatchEvent(new CustomEvent('af_youtube_bridge_event', {
        detail: { type, data }
      }));
    } catch (e) {
      console.warn('[AF YouTube Injected] Dispatch error:', e);
    }
  }

  function getCaptionTracks() {
    let tracks = null;
    let videoTitle = '';

    // 1. Check movie_player
    try {
      const player = document.getElementById('movie_player');
      if (player && typeof player.getPlayerResponse === 'function') {
        const resp = player.getPlayerResponse();
        tracks = resp?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
        videoTitle = resp?.videoDetails?.title || '';
      }
    } catch (e) {}

    // 2. Fallback to ytInitialPlayerResponse
    if (!tracks || !Array.isArray(tracks)) {
      try {
        if (window.ytInitialPlayerResponse) {
          tracks = window.ytInitialPlayerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
          if (!videoTitle) {
            videoTitle = window.ytInitialPlayerResponse?.videoDetails?.title || '';
          }
        }
      } catch (e) {}
    }

    if (!videoTitle) {
      const titleEl = document.querySelector('h1.ytd-watch-metadata yt-formatted-string, #title h1, h1.title');
      videoTitle = titleEl ? titleEl.textContent.trim() : document.title.replace(' - YouTube', '').trim();
    }

    const cleanTracks = [];
    if (Array.isArray(tracks)) {
      for (const t of tracks) {
        if (!t.baseUrl) continue;
        const lang = t.languageCode || 'en';
        const name = t.name?.simpleText || lang;
        const isAsr = t.kind === 'asr';
        const isEnglish = lang.toLowerCase().startsWith('en');

        cleanTracks.push({
          baseUrl: t.baseUrl,
          language: lang,
          label: `${name}${isAsr ? ' (Tự động)' : ''}`,
          isEnglish: isEnglish,
          isAutoGenerated: isAsr
        });
      }
    }

    return {
      title: videoTitle,
      tracks: cleanTracks
    };
  }

  function notifyTracks() {
    const info = getCaptionTracks();
    dispatchToContent('youtube_tracks_ready', info);
  }

  // Listen for request
  window.addEventListener('af_youtube_request_info', () => {
    notifyTracks();
  });

  // Listen for seek command
  window.addEventListener('af_youtube_seek', (e) => {
    try {
      const seconds = Number(e.detail && e.detail.seconds);
      if (isNaN(seconds) || seconds < 0) return;
      const player = document.getElementById('movie_player');
      if (player && typeof player.seekTo === 'function') {
        player.seekTo(seconds, true);
        player.playVideo();
      } else {
        const video = document.querySelector('video.html5-main-video, video');
        if (video) {
          video.currentTime = seconds;
          video.play();
        }
      }
    } catch (err) {}
  });

  // Watch for page navigation (yt-navigate-finish)
  window.addEventListener('yt-navigate-finish', () => {
    setTimeout(notifyTracks, 1200);
  });

  // Initial notify
  setTimeout(notifyTracks, 1500);

  console.log('[AF English] YouTube Injected Script initialized');
})();
