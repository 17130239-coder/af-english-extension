  /**
   * Look up word details: CEFR, IPA, Vietnamese definition, POS.
   * @param {string} word
   * @returns {{ cefr: string, ipa: string, vi: string, pos: string }|null}
   */
  function lookup(word) {
    if (!word) return null;
    const clean = String(word).toLowerCase().trim();
    let entry = DICT_DATA[clean];
    if (entry) {
      return {
        cefr: entry[0],
        ipa: entry[1],
        vi: entry[2],
        pos: entry[3]
      };
    }

    // Adverb suffix fallback (e.g. 'silently' -> 'silent', 'easily' -> 'easy')
    if (clean.endsWith('ly') && clean.length > 4) {
      const baseAdj = clean.slice(0, -2);
      entry = DICT_DATA[baseAdj] || DICT_DATA[baseAdj + 'e'] || DICT_DATA[clean.slice(0, -3) + 'y'];
      if (entry) {
        return {
          cefr: entry[0],
          ipa: entry[1],
          vi: 'một cách ' + entry[2],
          pos: 'adv'
        };
      }
    }

    // Plural noun / 3rd person suffix fallback (e.g. 'mysteries' -> 'mystery', 'boxes' -> 'box', 'cats' -> 'cat')
    if (clean.endsWith('ies') && clean.length > 4) {
      const base = clean.slice(0, -3) + 'y';
      if (DICT_DATA[base]) {
        return { cefr: DICT_DATA[base][0], ipa: DICT_DATA[base][1], vi: DICT_DATA[base][2], pos: DICT_DATA[base][3] };
      }
    } else if (clean.endsWith('es') && clean.length > 4) {
      const base = clean.slice(0, -2);
      if (DICT_DATA[base]) {
        return { cefr: DICT_DATA[base][0], ipa: DICT_DATA[base][1], vi: DICT_DATA[base][2], pos: DICT_DATA[base][3] };
      }
    } else if (clean.endsWith('s') && !clean.endsWith('ss') && clean.length > 3) {
      const base = clean.slice(0, -1);
      if (DICT_DATA[base]) {
        return { cefr: DICT_DATA[base][0], ipa: DICT_DATA[base][1], vi: DICT_DATA[base][2], pos: DICT_DATA[base][3] };
      }
    }

    // Past tense suffix fallback (e.g. 'discovered' -> 'discover', 'lived' -> 'live', 'studied' -> 'study')
    if (clean.endsWith('ied') && clean.length > 4) {
      const base = clean.slice(0, -3) + 'y';
      if (DICT_DATA[base]) {
        return { cefr: DICT_DATA[base][0], ipa: DICT_DATA[base][1], vi: DICT_DATA[base][2], pos: DICT_DATA[base][3] };
      }
    } else if (clean.endsWith('ed') && clean.length > 4) {
      const base1 = clean.slice(0, -2);
      const base2 = clean.slice(0, -1);
      const matched = DICT_DATA[base1] || DICT_DATA[base2];
      if (matched) {
        return { cefr: matched[0], ipa: matched[1], vi: matched[2], pos: matched[3] };
      }
    }

    // Gerund / participle suffix fallback (e.g. 'running' -> 'run', 'making' -> 'make', 'walking' -> 'walk')
    if (clean.endsWith('ing') && clean.length > 5) {
      const base1 = clean.slice(0, -3);
      const base2 = clean.slice(0, -3) + 'e';
      // Double consonant check: running -> run
      let base3 = null;
      if (base1.length >= 3 && base1[base1.length - 1] === base1[base1.length - 2]) {
        base3 = base1.slice(0, -1);
      }
      const matched = DICT_DATA[base1] || DICT_DATA[base2] || (base3 && DICT_DATA[base3]);
      if (matched) {
        return { cefr: matched[0], ipa: matched[1], vi: matched[2], pos: matched[3] };
      }
    }

    return null;
  }

  /**
   * Estimate CEFR level based on word length and dictionary.
   */
  function getLevel(word) {
    const entry = lookup(word);
    if (entry) return entry.cefr;

    const len = (word || '').length;
    if (len <= 4) return 'A2';
    if (len <= 7) return 'B1';
    if (len <= 10) return 'B2';
    return 'C1';
  }

  return Object.freeze({
    lookup,
    getLevel,
    DATA: DICT_DATA
  });
